"""Small helpers that render pipeline results to Markdown/JSON under ml/reports/."""

from __future__ import annotations

import json
from pathlib import Path

from rideros_ml.data.license_check import LicenseCheck
from rideros_ml.data.validate import ValidationReport


def write_json(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False, default=str), encoding="utf-8")


def validation_markdown(
    report: ValidationReport,
    license_checks: list[LicenseCheck],
    manifest: dict,
    tail_profile: dict,
) -> str:
    lines = [
        "# Data Validation Report - Meituan INFORMS TSL (all_waybill_info)",
        "",
        "Generated by `rideros-ml validate`. Gate result: "
        + ("**PASS**" if report.ok and all(c.present for c in license_checks) else "**FAIL**"),
        "",
        "## Source",
        f"- Repository: `{manifest['repo']}` @ `{manifest['commit']}`",
    ]
    for name, f in manifest["files"].items():
        lines.append(f"- `{name}`: {f['bytes']:,} bytes, sha256 `{f['sha256']}`")
    for name, f in manifest.get("extracted", {}).items():
        lines.append(f"- extracted `{name}`: {f['bytes']:,} bytes, sha256 `{f['sha256']}`")
    lines += ["", "## License clauses (License.txt)", "", "| Clause | Present |", "|---|---|"]
    lines += [f"| {c.clause} | {'yes' if c.present else '**NO**'} |" for c in license_checks]
    lines += ["", "## Checks", "", "| Check | Severity | Result | Detail |", "|---|---|---|---|"]
    for c in report.checks:
        result = "pass" if c.passed else ("**FAIL**" if c.severity == "error" else "warn")
        detail = c.detail + (f" `{json.dumps(c.data, default=str)}`" if c.data else "")
        lines.append(f"| {c.name} | {c.severity} | {result} | {detail} |")
    lines += [
        "",
        "## Target tail profile (train period only, before cleaning rule)",
        "",
        "Order-to-pickup minutes for picked-up, non-prebook orders with local order date <= train_last_date.",
        "",
        "```json",
        json.dumps(tail_profile, indent=2),
        "```",
    ]
    return "\n".join(lines) + "\n"
